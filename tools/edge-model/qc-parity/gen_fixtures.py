#!/usr/bin/env python3
"""
Generate the expectations for the JVM test QcParityPreprocessTest — no image files in git.

Inputs are synthetic images built from a pure-integer formula (synthetic_image below) that the
Kotlin test reproduces bit-for-bit, so only a small manifest is committed:

  packages/openchs-android/android/app/src/test/resources/qc-parity/manifest.txt
    name width height seed newW newH offsetX offsetY sha256(resized BGR) sha256(final BGR u8)

"resized" = cv2.resize(INTER_CUBIC) to the letterbox size; "final" = the QC notebook's uint8 BGR
image after white balance / round / convertScaleAbs (model tensor = final / 255, B,G,R planes).

Usage:
  python3 gen_fixtures.py                    # rewrite manifest.txt
  python3 gen_fixtures.py --debug-png DIR    # also write input/resized/final PNGs to DIR (don't commit)
"""
import argparse
import hashlib
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import qc_reference as qc  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
OUT = REPO / "packages/openchs-android/android/app/src/test/resources/qc-parity"
M32 = 0xFFFFFFFF

# name, width, height, seed — square, 4:3, 3:4, odd size, SIMD-tail (163-px width), upscale
CASES = [
    ("square_640", 640, 640, 1),
    ("landscape_4x3_800", 800, 600, 2),
    ("portrait_3x4_600", 600, 800, 3),
    ("odd_1001x777", 1001, 777, 4),
    ("tall_tail_581x913", 581, 913, 5),
    ("small_upscale_70x50", 70, 50, 6),
]


def synthetic_image(w, h, seed):
    """Photo-like BGR uint8 image from integer arithmetic only (mirrored in QcParityPreprocessTest.kt).

    Per channel c (0=B,1=G,2=R): a diagonal gradient + 4 soft-edged discs + hash noise in [-12, 12].
    """
    y, x = np.mgrid[0:h, 0:w].astype(np.int64)
    img = np.zeros((h, w, 3), np.int64)
    for c in range(3):
        k = seed * 31 + c * 7
        base = 40 + (k * 13) % 90
        v = base + (x * (60 + k % 50)) // w + (y * (40 + (k * 3) % 70)) // h
        for d in range(4):
            cx = (k * 97 + d * 211) % w
            cy = (k * 53 + d * 137) % h
            r = max(4, min(w, h) * (10 + (k + d * 17) % 25) // 100)
            amp = (k * 29 + d * 61) % 141 - 70
            d2 = (x - cx) ** 2 + (y - cy) ** 2
            v = v + np.where(d2 < r * r, amp, np.where(d2 < 4 * r * r, amp // 2, 0))
        hsh = ((x * 73856093) ^ (y * 19349663) ^ ((c + 1) * 83492791) ^ (seed * 2654435761)) & M32
        hsh = (hsh * 2246822519) & M32
        v = v + (hsh >> 16) % 25 - 12
        img[..., c] = np.clip(v, 0, 255)
    return img.astype(np.uint8)


def sha(a):
    return hashlib.sha256(np.ascontiguousarray(a).tobytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--debug-png")
    a = ap.parse_args()
    lines = []
    for name, w, h, seed in CASES:
        img = synthetic_image(w, h, seed)
        resized, padded = qc.letterbox(img)
        final = qc.white_balance_u8(padded)
        nh, nw = resized.shape[:2]
        lines.append(f"{name} {w} {h} {seed} {nw} {nh} {(256 - nw) // 2} {(256 - nh) // 2} {sha(resized)} {sha(final)}")
        print(f"{name:22s} {w}x{h} -> {nw}x{nh}")
        if a.debug_png:
            d = Path(a.debug_png); d.mkdir(parents=True, exist_ok=True)
            for tag, im in (("input", img), ("resized", resized), ("final", final)):
                cv2.imwrite(str(d / f"{name}_{tag}.png"), im)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "manifest.txt").write_text(
        "# name width height seed newW newH offsetX offsetY sha256(resized BGR) sha256(final BGR u8)\n"
        "# generated by tools/edge-model/qc-parity/gen_fixtures.py from qc_reference.py (cv2 " + cv2.__version__ + ")\n"
        + "\n".join(lines) + "\n")
    print(f"wrote {OUT / 'manifest.txt'}")


if __name__ == "__main__":
    main()
